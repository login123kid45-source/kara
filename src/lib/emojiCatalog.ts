export function applyEmojiSkinTone(emoji: string, modifier: string, supportsSkinTone?: boolean): string {
  if (!modifier || !supportsSkinTone) return emoji;
  // Insert skin tone modifier after the first code point
  const codePoints = Array.from(emoji);
  if (codePoints.length === 0) return emoji;
  if (codePoints.length === 1) {
    return codePoints[0] + modifier;
  }
  // Remove variation selector FE0F if present right after base char before adding skin tone
  if (codePoints[1] === '\uFE0F') {
    return codePoints[0] + modifier + codePoints.slice(2).join('');
  }
  return codePoints[0] + modifier + codePoints.slice(1).join('');
}
